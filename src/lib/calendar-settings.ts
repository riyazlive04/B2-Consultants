/**
 * Synamate's "Calendar settings" list, derived rather than stored.
 *
 * B2 has no Calendar table and does not need one: a discovery calendar IS a named weekly pattern
 * in Console → Availability, and the strategy calendar IS the one owner in the SSS config. What
 * this adds is the thing neither screen says - whether each of them is actually producing slots
 * anybody can book. A pattern that is switched on, has weekdays, and still offers nothing is the
 * failure that emptied the production calendar once already.
 */

import { calendarRef, ownerColor, type CalType } from "./calendar-event";

export type SlotTally = {
  /** `null` = the unassigned pile. */
  ownerId: string | null;
  /** OPEN slots from now to the horizon - what a prospect could actually take. */
  openAhead: number;
  /** The last slot of any status in the future, so a drained calendar can say when it ran out. */
  lastAheadAt: string | null;
};

export type SettingStatus = "ACTIVE" | "NO_AVAILABILITY" | "SWITCHED_OFF" | "NO_DAYS" | "NO_OWNER";

export const SETTING_STATUS_LABELS: Record<SettingStatus, string> = {
  ACTIVE: "Active",
  NO_AVAILABILITY: "No availability",
  SWITCHED_OFF: "Switched off",
  NO_DAYS: "No days chosen",
  NO_OWNER: "Owner not set",
};

export type CalendarSetting = {
  key: string;
  name: string;
  group: CalType;
  ownerId: string | null;
  ownerName: string;
  durationMins: number | null;
  /** "Mon, Tue, Wed · 15:00-18:00", or why there is no schedule to show. */
  schedule: string;
  openAhead: number;
  /** The same hue this calendar's cards wear on the grid - one person, one colour, everywhere. */
  color: string;
  status: SettingStatus;
  /** One sentence saying what to do about this row's status. */
  detail: string;
  editHref: string;
};

type Pattern = {
  id: string;
  name: string;
  enabled: boolean;
  weekdays: string[];
  startTime: string;
  endTime: string;
  durationMins: number;
  assignedToId: string;
};

const DAY_LABEL: Record<string, string> = {
  MON: "Mon", TUE: "Tue", WED: "Wed", THU: "Thu", FRI: "Fri", SAT: "Sat", SUN: "Sun",
};
const DAY_ORDER = ["MON", "TUE", "WED", "THU", "FRI", "SAT", "SUN"];

const tallyFor = (tallies: SlotTally[], ownerId: string | null) =>
  tallies.find((t) => (t.ownerId ?? "") === (ownerId ?? "")) ?? { ownerId, openAhead: 0, lastAheadAt: null };

const nameFor = (team: { id: string; name: string | null }[], id: string | null) =>
  (id ? team.find((u) => u.id === id)?.name : null) ?? (id ? "Unknown user" : "Unassigned");

/** Position in the name-sorted team is what decides a person's colour everywhere else. */
const colorFor = (team: { id: string }[], id: string | null) =>
  ownerColor(id ? team.findIndex((u) => u.id === id) : -1);

function discoStatus(p: Pattern, openAhead: number): SettingStatus {
  if (!p.enabled) return "SWITCHED_OFF";
  if (p.weekdays.length === 0) return "NO_DAYS";
  return openAhead > 0 ? "ACTIVE" : "NO_AVAILABILITY";
}

const DETAIL: Record<SettingStatus, string> = {
  ACTIVE: "Generating slots, and prospects can book them.",
  NO_AVAILABILITY: "No open slots ahead - the top-up runs hourly, so check the hours and horizon.",
  SWITCHED_OFF: "Switched off, so the hourly top-up skips it and no slots are created.",
  NO_DAYS: "Switched on but no weekdays are selected, so it fits no slots at all.",
  NO_OWNER: "Nobody runs this calendar yet, so no slots can be laid out.",
};

/**
 * One row per discovery pattern, one per owner holding slots NO pattern explains, and one for the
 * strategy session calendar.
 *
 * The middle case is not decoration: slots generated by hand (or by a pattern somebody later
 * deleted) are real bookable time that no settings screen would otherwise account for.
 */
export function calendarSettingRows(
  input: {
    patterns: Pattern[];
    sss: { ownerId: string | null; slotDurationMins: number };
    discoTallies: SlotTally[];
    sssTallies: SlotTally[];
  },
  team: { id: string; name: string | null }[],
): CalendarSetting[] {
  const rows: CalendarSetting[] = [];
  const explained = new Set<string>();

  for (const p of input.patterns) {
    const ownerId = p.assignedToId || null;
    explained.add(ownerId ?? "");
    const { openAhead } = tallyFor(input.discoTallies, ownerId);
    const status = discoStatus(p, openAhead);
    const days = [...p.weekdays].sort((a, b) => DAY_ORDER.indexOf(a) - DAY_ORDER.indexOf(b)).map((d) => DAY_LABEL[d] ?? d);
    rows.push({
      key: `disco:${p.id}`,
      name: p.name,
      group: "DISCO",
      ownerId,
      ownerName: nameFor(team, ownerId),
      durationMins: p.durationMins,
      schedule: days.length ? `${days.join(", ")} · ${p.startTime}-${p.endTime}` : "No weekdays selected",
      openAhead,
      color: colorFor(team, ownerId),
      status,
      detail: DETAIL[status],
      editHref: "/console?area=sales&panel=availability",
    });
  }

  for (const t of input.discoTallies) {
    const id = t.ownerId ?? "";
    if (explained.has(id) || t.openAhead === 0) continue;
    rows.push({
      key: `disco-loose:${id || "none"}`,
      name: `Hand-made slots - ${nameFor(team, t.ownerId)}`,
      group: "DISCO",
      ownerId: t.ownerId,
      ownerName: nameFor(team, t.ownerId),
      durationMins: null,
      schedule: "No pattern - added by hand",
      openAhead: t.openAhead,
      color: colorFor(team, t.ownerId),
      status: "ACTIVE",
      detail: "Bookable slots that no calendar pattern explains. They stop when they run out.",
      editHref: "/bookings/availability",
    });
  }

  const sssOwner = input.sss.ownerId;
  const sssOpen = tallyFor(input.sssTallies, sssOwner).openAhead;
  const sssStatus: SettingStatus = !sssOwner ? "NO_OWNER" : sssOpen > 0 ? "ACTIVE" : "NO_AVAILABILITY";
  rows.push({
    key: "sss",
    name: "Solution Strategy Session",
    group: "SSS",
    ownerId: sssOwner,
    ownerName: nameFor(team, sssOwner),
    durationMins: input.sss.slotDurationMins,
    schedule: "Laid out from the SSS Calendar tab",
    openAhead: sssOpen,
    // Strategy sessions share one colour on the grid, whoever runs them.
    color: calendarRef("SSS", null, 0).color,
    status: sssStatus,
    detail: DETAIL[sssStatus],
    editHref: "/bookings?tab=sss",
  });

  return rows;
}
